const HALLUCINATIONS = ["субтитры", "редактор субтитров", "корректор", "продолжение следует", "спасибо за просмотр", "подписывайтесь на канал", "ставьте лайки", "dimatorzok", "amara.org", "благодарю за внимание"];

/** Типографика по Ильяхову: короткие слова приклеиваются неразрывным пробелом к следующему */
export function typo(s) {
  return s.replace(/(?<=^|[\s«(])([А-Яа-яЁёA-Za-z]{1,2}|без|для|под|над|при|про|через|или|что|как|это|все|всё|она|оно|они|его|её|еще|ещё)\s+/g,
    (m, w) => w + '\u00A0');
}

export function headline(text, max = 70) {
  const line = (text || '').trim().split('\n').find(l => l.trim())?.trim() || '';
  if (line.length <= max) return line;
  const cut = line.slice(0, max);
  const sp = cut.lastIndexOf(' ');
  return (sp > max / 2 ? cut.slice(0, sp) : cut).replace(/[,.\s—-]+$/, '') + '…';
}

const URL_RE = /(https?:\/\/[^\s<>"]+|www\.[^\s<>"]+)/gi;
export function findUrls(text) { return [...(text || '').matchAll(URL_RE)].map(m => m[0].replace(/[.,)»]+$/, '')); }
export function normalizeUrl(u) { return /^http/i.test(u) ? u : 'https://' + u; }
export function domain(u) { try { return new URL(normalizeUrl(u)).host.replace(/^www\./, ''); } catch { return u; } }
/** Текст на куски: обычный и ссылки */
export function splitLinks(text) {
  const out = []; let last = 0;
  for (const m of (text || '').matchAll(URL_RE)) {
    const v = m[0].replace(/[.,)»]+$/, '');
    if (m.index > last) out.push({ t: text.slice(last, m.index) });
    out.push({ t: v, url: normalizeUrl(v) });
    last = m.index + v.length;
  }
  if (last < (text || '').length) out.push({ t: text.slice(last) });
  return out;
}

export function cleanTranscript(raw) {
  return raw.split('\n').map(l => l.trim()).filter(l => l)
    .filter(l => !(HALLUCINATIONS.some(h => l.toLowerCase().includes(h)) && l.length < 80))
    .filter(l => !/^[\[(*].*[\])*]$/.test(l))
    .join(' ').replace(/\s+/g, ' ').trim();
}

